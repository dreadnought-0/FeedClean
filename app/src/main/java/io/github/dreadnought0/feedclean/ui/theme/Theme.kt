/** Extra semantic colors that Material 3's scheme does not cover. Read via [FeedCleanTheme.extraColors]. */
@Immutable
data class FeedCleanExtraColors(
    /** Tint for a passing ("✓") status item. Failing items use `colorScheme.error`. */
    val statusOk: Color,
)

private val LightExtraColors = FeedCleanExtraColors(statusOk = StatusOkLight)
private val DarkExtraColors = FeedCleanExtraColors(statusOk = StatusOkDark)

private val LocalFeedCleanExtraColors = staticCompositionLocalOf { LightExtraColors }

/**
 * FeedClean's Material 3 theme.
 *
 * @param darkTheme follow the system dark setting by default.
 * @param dynamicColor use the wallpaper-based scheme (Android 12+; always available at minSdk 33). When false,
 *   the neutral teal/slate fallback scheme is used (also what previews show).
 */
@Composable
fun FeedCleanTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    val extraColors = if (darkTheme) DarkExtraColors else LightExtraColors

    CompositionLocalProvider(LocalFeedCleanExtraColors provides extraColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content,
        )
    }
}

/** Accessors for FeedClean-specific theme values. */
object FeedCleanTheme {
    /** Semantic colors beyond the Material 3 scheme. */
    val extraColors: FeedCleanExtraColors
        @Composable get() = LocalFeedCleanExtraColors.current
}
